"""Generates a WISP draft (.docx) following the structure of IRS Publication 5708.
The owner must review, complete and sign it: Gadyen drafts, a human approves."""
from datetime import date

from docx import Document
from docx.shared import Pt

STATUS_LABEL = {"pass": "In place", "warn": "Needs improvement", "fail": "Missing",
                "unknown": "To be confirmed"}


def build_wisp(path: str, practice: str, answers: dict, findings: list, domains: set) -> str:
    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(11)
    doc.add_heading(f"Written Information Security Plan (WISP)\n{practice}", 0)
    doc.add_paragraph(f"Draft generated by Gadyen Safeguard on {date.today().isoformat()}. "
                      "This draft must be reviewed, completed and signed by the practice. "
                      "It is security guidance, not legal advice.")

    def section(title, *paragraphs):
        doc.add_heading(title, 1)
        for p in paragraphs:
            doc.add_paragraph(p)

    small = answers.get("Q03") == "under_5000"
    section("1. Purpose, scope and applicable rules",
            "This plan describes how the practice protects the nonpublic personal information of "
            "its clients, as required by the FTC Safeguards Rule (16 CFR Part 314), IRS "
            "Publications 4557 and 5708, and, for Massachusetts residents, 201 CMR 17.00.",
            "Size: the practice reports information on "
            + ("fewer than 5,000 consumers; some written elements of 16 CFR 314.4 are not "
               "required, but the core program is." if small else "5,000 or more consumers; "
               "all elements of 16 CFR 314.4 apply."))
    section("2. Qualified Individual",
            f"Responsible person: {answers.get('Q04') or '[TO BE DESIGNATED]'}. This person "
            "implements and supervises this plan and reports on it at least once a year.")
    places = ", ".join(answers.get("Q08") or []) or "[TO BE COMPLETED]"
    section("3. Inventory of client information",
            f"Locations reported: {places}. Email domain(s): {', '.join(sorted(domains)) or 'none'}.",
            "List every system, device and service provider that stores or processes client data.")
    doc.add_heading("4. Risk assessment (from Gadyen Safeguard checks)", 1)
    table = doc.add_table(rows=1, cols=4)
    table.style = "Light Grid Accent 1"
    for cell, text in zip(table.rows[0].cells, ["Control", "Target", "Status", "Detail"]):
        cell.text = text
    for f in findings:
        row = table.add_row().cells
        row[0].text = f"{f['control_id']} {f['title']}"
        row[1].text = f.get("target", "") or "practice"
        row[2].text = STATUS_LABEL.get(f["status"], f["status"])
        row[3].text = f["detail"]
    section("5. Safeguards",
            "Access control and least privilege; multi-factor authentication on email, tax "
            "software and remote access; encryption of client data in transit and at rest "
            "(including laptops and portable media); the IRS 'Security Six' (antivirus, "
            "firewall, MFA, backups, drive encryption, VPN); secure configuration and change "
            "management; logging of access to client data.")
    section("6. Employee training", "All personnel with access to client data, including "
            "seasonal staff, complete security awareness training at hiring and every year.")
    section("7. Service provider oversight", "Providers are selected with due diligence, bound "
            "by contract to protect client data, and reviewed periodically.")
    section("8. Monitoring and testing", "Gadyen Safeguard re-checks external configuration "
            "monthly. The Qualified Individual reviews results and this plan at least annually "
            "and after any significant change.")
    section("9. Incident response and notification", "Steps: contain, assess, notify. Report "
            "data theft to the IRS Stakeholder Liaison; notify the FTC within 30 days of "
            "discovery when unencrypted information of 500 or more consumers is involved; "
            "follow Massachusetts notification requirements (M.G.L. c. 93H).")
    section("10. Review history and approval",
            "Version 1 - Approved by: ______________________   Date: ____________")
    doc.save(path)
    return path
